def parse_remote_location_data(raw_data):
    """
    Remote Location RAO verilerini parse eder.
    12 sütun: Surge_X, Surge_Y, Sway_X, Sway_Y, Heave_X, Heave_Y, 
              Roll_X, Roll_Y, Pitch_X, Pitch_Y, Yaw_X, Yaw_Y
    """
    lines = raw_data.strip().split('\n')
    
    surge_x, surge_y = [], []
    sway_x, sway_y = [], []
    heave_x, heave_y = [], []
    roll_x, roll_y = [], []
    pitch_x, pitch_y = [], []
    yaw_x, yaw_y = [], []
    
    for line in lines:
        parts = line.split('\t')
        if len(parts) >= 12:
            surge_x.append(float(parts[0].replace(',', '.')))
            surge_y.append(float(parts[1].replace(',', '.')))
            sway_x.append(float(parts[2].replace(',', '.')))
            sway_y.append(float(parts[3].replace(',', '.')))
            heave_x.append(float(parts[4].replace(',', '.')))
            heave_y.append(float(parts[5].replace(',', '.')))
            roll_x.append(float(parts[6].replace(',', '.')))
            roll_y.append(float(parts[7].replace(',', '.')))
            pitch_x.append(float(parts[8].replace(',', '.')))
            pitch_y.append(float(parts[9].replace(',', '.')))
            yaw_x.append(float(parts[10].replace(',', '.')))
            yaw_y.append(float(parts[11].replace(',', '.')))
    
    return {
        'surge_x': np.array(surge_x), 'surge_y': np.array(surge_y),
        'sway_x': np.array(sway_x), 'sway_y': np.array(sway_y),
        'heave_x': np.array(heave_x), 'heave_y': np.array(heave_y),
        'roll_x': np.array(roll_x), 'roll_y': np.array(roll_y),
        'pitch_x': np.array(pitch_x), 'pitch_y': np.array(pitch_y),
        'yaw_x': np.array(yaw_x), 'yaw_y': np.array(yaw_y)
    }


