# =============================================================================
# DATA PARSING
# =============================================================================

lines = raw_data.strip().split('\n')
heave_freq, heave_rao = [], []
roll_freq, roll_rao = [], []
pitch_freq, pitch_rao = [], []
added_res_freq, added_res = [], []

for line in lines:
    values = [float(v.replace(',', '.')) for v in line.split('\t')]
    heave_freq.append(values[0])
    heave_rao.append(values[1])
    roll_freq.append(values[2])
    roll_rao.append(values[3])
    pitch_freq.append(values[4])
    pitch_rao.append(values[5])
    added_res_freq.append(values[6])
    added_res.append(values[7])

# =============================================================================
# FIGURE GENERATION - Academic Style
# =============================================================================

fig, ax1 = plt.subplots(figsize=(14, 8))

# Academic color palette
HEAVE_COLOR = '#E91E63'      # Magenta/Pink
ROLL_COLOR = '#00897B'       # Teal
PITCH_COLOR = '#FFB300'      # Amber/Gold
ADDED_RES_COLOR = '#8D6E63'  # Brown

# Primary Y-axis (RAO Transfer Function)
ax1.set_xlabel('Encounter Frequency (rad/s)', fontsize=12, fontweight='bold')
ax1.set_ylabel('RAO Transfer Function', fontsize=12, fontweight='bold')
ax1.plot(heave_freq, heave_rao, color=HEAVE_COLOR, linewidth=1, label='Heave RAO')
ax1.plot(roll_freq, roll_rao, color=ROLL_COLOR, linewidth=1, label='Roll RAO')
ax1.plot(pitch_freq, pitch_rao, color=PITCH_COLOR, linewidth=1, label='Pitch RAO')
ax1.tick_params(axis='y', labelsize=10)
ax1.tick_params(axis='x', labelsize=10)
ax1.set_xlim(0.35, 3.05)
ax1.set_ylim(0, 1.1)
ax1.grid(True, linestyle='--', alpha=0.3, color='gray', linewidth=0.5)

# Secondary Y-axis (Added Resistance)
ax2 = ax1.twinx()
ax2.set_ylabel('Added Resistance (kN/m²)', fontsize=12, fontweight='bold')
ax2.plot(added_res_freq, added_res, color=ADDED_RES_COLOR, linewidth=1.8, label='Added Resistance')
ax2.tick_params(axis='y', labelsize=10)
ax2.set_ylim(100, 300)

# Add curve labels on the plot
ax1.text(0.55, 0.60, 'Heave RAO', color=HEAVE_COLOR, fontsize=11, 
         fontweight='bold', ha='center', va='bottom',
         bbox=dict(boxstyle='round,pad=0.3', facecolor='white', edgecolor=HEAVE_COLOR, linewidth=1.5))

ax1.text(0.50, 0.90, 'Pitch RAO', color=PITCH_COLOR, fontsize=11,
         fontweight='bold', ha='center', va='center',
         bbox=dict(boxstyle='round,pad=0.3', facecolor='white', edgecolor=PITCH_COLOR, linewidth=1.5))

ax2.text(2.5, 230, 'Added Resistance', 
         color=ADDED_RES_COLOR, fontsize=11, fontweight='bold', ha='center', va='center',
         bbox=dict(boxstyle='round,pad=0.3', facecolor='white', edgecolor=ADDED_RES_COLOR, linewidth=1.5))

# Combined legend
lines1, labels1 = ax1.get_legend_handles_labels()
lines2, labels2 = ax2.get_legend_handles_labels()
ax1.legend(lines1 + lines2, labels1 + labels2, 
          loc='upper right', frameon=True, fontsize=10,
          title='CG RAOs', title_fontsize=11, fancybox=False, 
          edgecolor='black', framealpha=0.95, shadow=False)

# Background color
ax1.set_facecolor('#F5F5F5')

# Optimize layout
plt.tight_layout()

# Save figures
plt.savefig('rao_grafik.png', dpi=300, bbox_inches='tight', facecolor='white')
plt.savefig('rao_grafik.pdf', bbox_inches='tight', facecolor='white')
